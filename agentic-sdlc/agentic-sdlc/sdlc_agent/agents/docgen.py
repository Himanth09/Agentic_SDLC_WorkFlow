"""DocGenerator: documentation derived from the same sources as the code.

The API reference and README endpoint table are rendered *from the contract*,
configuration docs from the resolved settings, ADRs from the trade-off
records - so documentation cannot drift from what was built.
"""
# Store annotations as strings.
from __future__ import annotations

# time: today's date for the changelog entry.
import time

# get_pack returns None for unknown domains; require_pack raises.
from ..knowledge import get_pack, require_pack
# Core data models.
from ..models import FileChange, NormalizedRequirement, TaskSpec
# Agent base class and result container.
from .base import Agent, AgentResult


# Agent that writes README, API reference, runbook, ADRs, changelog and change notes.
class DocGenerator(Agent):
    # Registry name used by TaskSpec.agent.
    name = "docgen"

    # Entry point: build documents for the scenario, write and record them.
    def run(self, ctx, task: TaskSpec) -> AgentResult:
        # Analysed requirement.
        req: NormalizedRequirement = ctx.board.require("requirement")
        # Brownfield: changelog + reviewer change notes; otherwise full greenfield docs.
        if task.params.get("mode") == "brownfield":
            changes = self._brownfield(ctx, req)
        else:
            changes = self._greenfield(ctx, req)
        # Attribute each document to this task and write it through the guard.
        for ch in changes:
            ch.produced_by = task.id
            ctx.guard.apply(ch)
        # Register the documents as artifacts.
        ctx.board.append("artifacts", changes, producer=task.id)
        # Report how many documents were produced.
        return AgentResult(notes=[f"{len(changes)} documents"])

    # ------------------------------------------------------------ greenfield
    # Greenfield docs rendered from the API contract, settings and trade-offs.
    def _greenfield(self, ctx, req: NormalizedRequirement) -> list[FileChange]:
        # OpenAPI contract published by the Architect (single source of truth for endpoints).
        spec = ctx.board.require("api_contract")
        # Domain pack (for ADRs).
        pack = get_pack(req.domain)
        # Resolved settings shown as configuration defaults.
        s = req.settings
        # Flatten the contract into (METHOD, path, operation) triples.
        ops = [(m.upper(), p, op) for p, item in spec["paths"].items() for m, op in item.items()]
        # Markdown rows for the README endpoint table (auth = API key if the op declares security).
        endpoint_rows = "\n".join(f"| `{m}` | `{p}` | {op['summary']} | "
                                  f"{'API key' if op.get('security') else 'public'} |" for m, p, op in ops)
        # README template; endpoint table and config defaults are interpolated from contract/settings.
        readme = f"""# URL Shortener Service

{req.summary}

Generated by the agentic SDLC pipeline from the requirement:

> {req.raw}

## Quick start

```bash
python -m pytest                                   # unit + integration + contract tests
SHORTENER_API_KEYS=dev-key python -m shortener.main  # serves http://127.0.0.1:8080
curl -s -X POST localhost:8080/api/v1/links -H 'Content-Type: application/json' \\
     -H 'X-API-Key: dev-key' -d '{{"url": "https://example.com/very/long/path"}}'
curl -si localhost:8080/<code>                     # 302 -> target
curl -s localhost:8080/api/v1/links/<code>/stats   # click analytics
```

No third-party runtime dependencies (Python >= 3.10 standard library).

## Endpoints

| Method | Path | Purpose | Auth |
|---|---|---|---|
{endpoint_rows}

Full contract: [`openapi.yaml`](openapi.yaml) - reference: [docs/API.md](docs/API.md).

## Configuration

Defaults were resolved at the requirements gate; override with environment variables.

| Variable | Default | Meaning |
|---|---|---|
| `SHORTENER_CODE_LENGTH` | `{s['code_length']}` | Random base62 code length |
| `SHORTENER_CREATE_RATE_PER_MIN` | `{s['create_rate_per_min']}` | Link creations per client per minute |
| `SHORTENER_REQUIRE_API_KEY` | `{s['require_api_key']}` | Require `X-API-Key` on write endpoints |
| `SHORTENER_API_KEYS` | *(empty)* | Comma-separated accepted keys |
| `SHORTENER_ANALYTICS_IP_MODE` | `{s['analytics_ip_mode']}` | `hash` (salted daily hash) or `drop` |
| `SHORTENER_ANALYTICS_RETENTION_DAYS` | `{s['analytics_retention_days']}` | Raw click-event retention |
| `SHORTENER_DEFAULT_TTL_DAYS` | `{s['default_ttl_days']}` | Default link lifetime (0 = never) |
| `SHORTENER_ALLOW_CUSTOM_ALIAS` | `{s['allow_custom_alias']}` | Allow caller-chosen aliases |
| `SHORTENER_DB_PATH` | `shortener.db` | SQLite file (dev adapter) |
| `SHORTENER_BASE_URL` | `http://localhost:8080` | Prefix for `short_url` |
| `SHORTENER_IP_HASH_SALT` | random per process | Set explicitly for stable unique-visitor counts |

## Layout

```
shortener/   config, domain, codes, repository, cache, ratelimit, analytics, service, http, main
tests/       unit/ and integration/ (API, contract, persistence, concurrency)
docs/        architecture.md, API.md, RUNBOOK.md, adr/
```

See [docs/architecture.md](docs/architecture.md) for design, scaling plan and trade-offs.
"""
        # API reference document header (version taken from the contract).
        api = ["# API reference", "", f"Generated from `openapi.yaml` ({spec['info']['version']}). "
               "Errors use `application/problem+json`.", ""]
        # One section per operation.
        for m, p, op in ops:
            # Heading, operationId and whether an API key is required.
            api += [f"## `{m} {p}` - {op['summary']}", f"operationId: `{op['operationId']}`"
                    + ("  |  requires `X-API-Key`" if op.get("security") else ""), ""]
            # One bullet per parameter (location, name, required flag, schema).
            for prm in op.get("parameters", []):
                api.append(f"- {prm['in']} parameter `{prm['name']}`"
                           f"{' (required)' if prm.get('required') else ''}: `{prm['schema']}`")
            # JSON request-body schema, if the operation has one.
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            # List body fields, marking required ones with '*'.
            if body:
                api.append("- body fields: " + ", ".join(
                    f"`{k}`{'*' if k in body.get('required', []) else ''}" for k in body["properties"]))
            # Response status table.
            api += ["", "| Status | Meaning |", "|---|---|"]
            api += [f"| {code} | {r['description']} |" for code, r in op["responses"].items()]
            # Blank line between operations.
            api.append("")
        # Static operations runbook (health, metrics, failure modes, operations).
        runbook = """# Runbook

## Health
`GET /healthz` -> `{"status": "ok", "analytics_backlog": N, "analytics_dropped": M}`.
Alert when `analytics_dropped` increases (analytics capacity) or backlog stays > 10k (store slow).

## Key metrics (production)
- redirect p50/p99 latency, 5xx rate, 404/410 rate (spikes = enumeration or expired campaign)
- cache hit ratio (target > 90%), store read/write throttles
- link creations per key, 429 rate (abuse)

## Failure modes
| Symptom | Likely cause | Action |
|---|---|---|
| 503 `code_space_exhausted` | code length too short for the volume | raise `SHORTENER_CODE_LENGTH` |
| rising `analytics_dropped` | analytics store slow/unavailable | redirects unaffected by design; scale/repair store |
| 429 for legitimate client | per-key limit too low | raise `SHORTENER_CREATE_RATE_PER_MIN` for that tier |
| phishing report | abuse | `DELETE /api/v1/links/{code}` with owner key; add host to blocklist |

## Operations
- Graceful shutdown (SIGTERM) flushes buffered click events.
- Retention: schedule `SQLiteAnalyticsStore.purge_before(now - retention)` daily
  (production: S3 lifecycle rule on raw events).
"""
        # The three core documents.
        changes = [FileChange("project/README.md", "create", readme),
                   FileChange("project/docs/API.md", "create", "\n".join(api)),
                   FileChange("project/docs/RUNBOOK.md", "create", runbook)]
        # One ADR file per trade-off (ADR-001.md, ADR-002.md, ...).
        for i, t in enumerate(pack.tradeoffs if pack else [], 1):
            changes.append(FileChange(
                f"project/docs/adr/ADR-{i:03d}.md", "create",
                f"# ADR-{i:03d}: {t.decision}\n\nStatus: accepted\n\n## Decision\n{t.chosen}\n\n"
                f"## Alternatives considered\n{t.alternatives}\n\n## Rationale and consequences\n"
                f"{t.rationale}\n"))
        # All greenfield documents.
        return changes

    # ------------------------------------------------------------ brownfield
    # Brownfield docs: prepend a CHANGELOG entry and write reviewer change notes.
    def _brownfield(self, ctx, req: NormalizedRequirement) -> list[FileChange]:
        # Impact analysis (matched recipes, roles, schema change flag).
        impact = ctx.board.require("impact")
        # Domain pack with the recipe definitions.
        pack = require_pack(req.domain)
        # Recipe objects for the matched recipe ids.
        recipes = [pack.brownfield_recipes[r] for r in impact["recipes"]]
        # Today's date (local time) for the changelog heading.
        today = time.strftime("%Y-%m-%d")
        # New changelog section.
        entry = [f"## Unreleased ({today})", ""]
        # One subsection per recipe.
        for r in recipes:
            # Recipes whose id starts with "fix" are bug fixes; everything else is an addition.
            kind = "Fixed" if r.id.startswith("fix") else "Added"
            entry.append(f"### {kind}\n- {r.title}")
            # Acceptance criteria as nested bullets.
            entry += [f"  - {c.text}" for c in r.criteria]
            entry.append("")
        # Document the automatic schema migration when the schema changes.
        if impact["schema_change"]:
            entry += ["### Migration", "- `links.expires_at REAL` is added automatically on start-up "
                      "(idempotent `ALTER TABLE`); no downtime, existing links never expire.", ""]
        # Workspace copy of the project.
        project = ctx.guard.safe_path("project")
        # Existing changelog (if any).
        changelog = project / "CHANGELOG.md"
        # Current changelog text, or a fresh header.
        prior = changelog.read_text(encoding="utf-8") if changelog.exists() else "# Changelog\n\n"
        # Split off the title block so the new entry goes right after it.
        head, _, rest = prior.partition("\n\n")
        # Reviewer-facing change notes.
        notes = ["# Change notes for reviewers", "", f"Requirement: {req.raw}", "",
                 "## What changed and why"]
        # Per-recipe section listing the roles/modules it touches.
        for r in recipes:
            notes += [f"### {r.title}", f"Touches roles: {', '.join(r.roles)} -> "
                      + ", ".join(f"`{impact['roles'][x]}`" for x in r.roles), ""]
        # API impact (conditional lines), then the rollout plan.
        notes += ["## API impact", "- `POST /links`: optional `ttl_seconds`; response adds `expires_at`; "
                  "taken alias now returns `409 Conflict` instead of silently overwriting"
                  if "fix_alias_overwrite" in impact["recipes"] else "- see impact analysis",
                  "- `GET /{code}`: may return `410 Gone` for expired links"
                  if impact["schema_change"] else "", "",
                  "## Rollout", "1. Deploy (migration runs on start-up, backward compatible).",
                  "2. Clients that relied on alias overwrite will now receive 409 - communicate this "
                  "behaviour change.", "3. Rollback: previous version ignores the extra column."]
        # Rewritten changelog (head + new entry + previous entries) and the change notes.
        return [FileChange("project/CHANGELOG.md", "create", f"{head}\n\n" + "\n".join(entry) + rest),
                FileChange("review/change_notes.md", "create", "\n".join(notes) + "\n")]
